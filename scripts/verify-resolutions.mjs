import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
process.env.RIV_RECORDS_FILE = `${mkdtempSync(`${tmpdir()}/riv-resolutions-`)}/records.jsonl`;
const { default: exchange } = await import(new URL('agent/tools/create_exchange.ts', root));
const { default: refund } = await import(new URL('agent/tools/create_return.ts', root));
const { default: eligibility } = await import(new URL('agent/tools/check_eligibility.ts', root));
const { listRecords } = await import(new URL('agent/lib/engine/records.ts', root));
const ctx = { session: { id: 'regression' } };
const input = { orderId: 'TSS-10588', returnProductId: 'TSS-WDR-001', replacementProductId: 'TSS-WDR-001', replacementSize: 'S', replacementColor: 'black', reasonLabel: 'quality_defect' };
const first = await exchange.execute(input, ctx);
assert.equal(first.created, true); assert.equal(first.outcome, 'REPLACEMENT'); assert.equal(first.priceDeltaInr, 0);
const second = await exchange.execute(input, ctx);
assert.equal(second.created, false); assert.equal(second.reasonCode, 'already_resolved');
const opposite = await refund.execute({ orderId: input.orderId, productId: input.returnProductId, reasonLabel: 'quality_defect' }, ctx);
assert.equal(opposite.created, false);
const later = eligibility.execute({ orderId: input.orderId, productId: input.returnProductId, reasonLabel: 'quality_defect' });
assert.equal(later.eligible, false);
assert.equal(listRecords('exchange').length, 1); assert.equal(listRecords('return').length, 0);
assert.equal(await exchange.approval(), 'user-approval'); assert.equal(await refund.approval(), 'user-approval');
const restarted = spawnSync(process.execPath, ['--input-type=module', '-e', `import { findResolution } from ${JSON.stringify(new URL('agent/lib/engine/records.ts', root).href)}; console.log(JSON.stringify(findResolution('TSS-10588','TSS-10588-1')));`], { encoding: 'utf8', env: process.env });
assert.equal(restarted.status, 0, restarted.stderr); assert.equal(JSON.parse(restarted.stdout).recordId, first.exchangeId);
console.log('PASS: defect replacement, duplicate and conflicting resolution rejection, updated eligibility, approval gates, persistent restart readback');
